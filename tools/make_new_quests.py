#!/usr/bin/env python3
"""Writes what tells Classic's quests from the ones Forever added
(NewQuests.lua), for the marker behind their titles. Classic's quest ids all
lie at or below one id, apart from a few events above it; a quest is new when
it is above that id and no such event, or one of the few new ids below it.
So quests of later patches count as new without a new list. Both clients'
QuestV2 tables come from wago.tools: Forever's and the last Classic client
before Season of Discovery (1.14.0). QuestV2 lacks quests without a completion
flag, so it cannot list Classic's quests itself. Run again only to check:

    python3 tools/make_new_quests.py 1.60.1.70862 1.14.0.40618
"""
import csv
import io
import os
import sys
import urllib.request

URL = "https://wago.tools/db2/QuestV2/csv?build={build}"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "NewQuests.lua")


def quest_ids(build):
    request = urllib.request.Request(URL.format(build=build), headers={"User-Agent": "ForeverQuestLog tools"})
    with urllib.request.urlopen(request, timeout=120) as response:
        ids = {int(r["ID"]) for r in csv.DictReader(io.StringIO(response.read().decode("utf-8")))}
    if not ids:
        sys.exit("wago.tools has no quests for build " + build)
    return ids


LAST_ID_SEARCH = 20000  # Classic's quests lie below; its events far above


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    forever_build, classic_build = sys.argv[1:]
    forever, classic = quest_ids(forever_build), quest_ids(classic_build)
    last = max(i for i in classic if i < LAST_ID_SEARCH)
    above = sorted(i for i in classic if i > last)
    below = sorted(i for i in forever - classic if i <= last)
    new = {i for i in forever if i in below or (i > last and i not in above)}
    if new != forever - classic:
        sys.exit("the rule misses quests: %s" % sorted((forever - classic) ^ new)[:20])
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("-- Generated by tools/make_new_quests.py from client builds %s (Forever) and %s (Classic): do not edit.\n"
                  "-- New = above CLASSIC_LAST_QUEST and no Classic event, or one of NEW_BELOW.\n"
                  "local _, ns = ...\n"
                  "ns.CLASSIC_LAST_QUEST = %d\n"
                  "ns.CLASSIC_EVENTS_ABOVE = { %s }\n"
                  "ns.NEW_QUESTS_BELOW = { %s }\n"
                  % (forever_build, classic_build, last, ", ".join(map(str, above)), ", ".join(map(str, below))))
    print(len(new), "new quests today; last Classic id", last, "+", len(above), "events,", len(below), "new below")


if __name__ == "__main__":
    main()
