# Map's name where AreaTable's differs (the task lists use Map's).
ALIASES = {"The Deadmines": ["Deadmines"], "The Stockade": ["Stormwind Stockade"],
           "Ahn'Qiraj Temple": ["Temple of Ahn'Qiraj"]}


def fetch(table, build, locale, name_field):
    url = URL.format(table=table, build=build, locale=locale)
    request = urllib.request.Request(url, headers={"User-Agent": "ForeverQuestLog tools"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return {r["ID"]: r[name_field] for r in csv.DictReader(io.StringIO(response.read().decode("utf-8")))}


def ids_by_name(names):
    found = {}
    for i, name in names.items():
        found.setdefault(name, []).append(i)
    return found


def main():
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    build = sys.argv[1] if len(sys.argv) == 2 else installed_build()
    tables = {(t, loc): fetch(t, build, loc, f) for t, f in (("AreaTable", "AreaName_lang"), ("Map", "MapName_lang"))
              for loc in LOCALES}
    area_ids = ids_by_name(tables["AreaTable", "enUS"])
    map_ids = ids_by_name(tables["Map", "enUS"])
    wanted = []  # (table, id, range)
    for name, levels in {**ZONES, **INSTANCES}.items():
        hits = [("AreaTable", i) for i in area_ids.get(name, [])]
        for alias in [name] + ALIASES.get(name, []):
            hits += [("Map", i) for i in map_ids.get(alias, [])]
        if not hits:
            sys.exit("no such place in build %s: %s" % (build, name))
        wanted += [(t, i, levels) for t, i in hits]
    lines = ["-- Generated by tools/make_zone_levels.py from client build %s: do not edit." % build,
             "-- Level ranges by place name per language; esMX uses esES, other languages English.",
             "local _, ns = ...",
             "local levels = {"]
    for locale in LOCALES:
        names = {}
        for table, i, levels in wanted:
            name = tables[table, locale].get(i) or tables[table, "enUS"][i]
            if name and names.setdefault(name, levels) != levels:
                sys.exit("%s: %s has two ranges" % (locale, name))
        lines.append("    %s = {" % locale)
        lines += ["        [%s] = { %d, %d }," % (lua_string(n), lo, hi) for n, (lo, hi) in sorted(names.items())]
        lines.append("    },")
        print(locale, len(names), "names")
    lines += ["}",
              'local locale = GetLocale() == "esMX" and "esES" or GetLocale()',
              "ns.ZoneLevelData = levels[locale] or levels.enUS",
              ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines))


if __name__ == "__main__":
    main()
