#!/usr/bin/env python3
"""Writes the level ranges of zones and instances per language (ZoneLevelData.lua).
Forever's client has none (C_Map.GetMapLevels gives 0), so the ranges below
are Classic's plus the guides' for Forever's new places. The names in each
language come from wago.tools (AreaTable: quest log headers and the map,
Map: the task lists' dungeon names). Run again after changing a range:

    python3 tools/make_zone_levels.py [1.60.1.70862]

Without a build it takes the installed Forever client's (.build.info).
"""
