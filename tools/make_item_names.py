#!/usr/bin/env python3
"""Writes the item names the task lists suggest (ItemNames/<locale>.lua). The
client cannot search items by name, so the addon ships the names of one client
build, read from wago.tools. Run again when a patch brings new items:

    python3 tools/make_item_names.py 1.60.1.70862
"""
import csv
import io
import os
import re
import sys
import urllib.request

URL = "https://wago.tools/db2/ItemSparse/csv?build={build}&locale={locale}"
# Blizzard's leftovers: no player can get these. Judged on the English names,
# so all languages list the same items.
LEFTOVER = re.compile(r"^(OLD|Deprecated|DEPRECATED|Monster - |UNUSED|Unused|\[|DEBUG|zz|QA|Test\b|\(DNT\)|\(OLD\))"
                      r"|\b(DEP|DEPRECATED|Deprecated|UNUSED|TEST|PH)\b")
# File's locale -> the client locales it serves; English serves all others.
LOCALES = {"deDE": ["deDE"], "esES": ["esES", "esMX"], "frFR": ["frFR"], "enUS": None}
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ItemNames")


def fetch(build, locale):
    request = urllib.request.Request(URL.format(build=build, locale=locale), headers={"User-Agent": "ForeverQuestLog tools"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode("utf-8"))))


def guard(locale):
    if LOCALES[locale] is None:
        others = [c for codes in LOCALES.values() if codes for c in codes]
        return " or ".join('GetLocale() == "%s"' % c for c in others)
    return " and ".join('GetLocale() ~= "%s"' % c for c in LOCALES[locale])


def lua_file(build, locale, rows, wanted):
    items = sorted((r["Display_lang"], int(r["ID"]), r["OverallQualityID"]) for r in rows if int(r["ID"]) in wanted)
    body = "".join("%d\t%s\t%s\n" % (i, q, name) for name, i, q in items)
    if "]==]" in body or any(c in name for name, _, _ in items for c in "\t\n\r"):
        sys.exit("a name of %s breaks the file format" % locale)
    return ("-- Generated by tools/make_item_names.py from client build %s: do not edit.\n"
            "-- One item per line: id, quality, name, sorted by name.\n"
            "local _, ns = ...\n"
            "if %s then return end\n"
            "ns.ItemNames = [==[\n%s]==]\n") % (build, guard(locale), body), len(items)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    build = sys.argv[1]
    english = fetch(build, "enUS")
    wanted = {int(r["ID"]) for r in english if r["Display_lang"] and not LEFTOVER.search(r["Display_lang"])}
    print("%d of %d items kept" % (len(wanted), len(english)))
    os.makedirs(OUT_DIR, exist_ok=True)
    for locale in LOCALES:
        rows = english if locale == "enUS" else fetch(build, locale)
        text, count = lua_file(build, locale, rows, wanted)
        if count != len(wanted):
            sys.exit("%s has %d names, expected %d" % (locale, count, len(wanted)))
        with open(os.path.join(OUT_DIR, locale + ".lua"), "w", encoding="utf-8", newline="\n") as out:
            out.write(text)
        print(locale, len(text.encode("utf-8")), "bytes")


if __name__ == "__main__":
    main()
