#!/usr/bin/env python3
"""Writes the dungeon and raid names the task lists suggest (PlaceNames.lua).
The client's map API and journal know no instances in Forever, so the addon
ships the names of one client build, read from wago.tools (table Map). Run
again when a patch brings new dungeons (tools/release does that itself):

    python3 tools/make_place_names.py [1.60.1.70862]

Without a build it takes the installed Forever client's (.build.info).
"""
import csv
import io
import os
import re
import sys
import urllib.request

URL = "https://wago.tools/db2/Map/csv?build={build}&locale={locale}"
INSTANCE_TYPES = {"1", "2"}  # party dungeon, raid
# Never open to players; judged on the English names.
LEFTOVER = re.compile(r"^(<|Test|CashTest|Emerald Dream$|Caverns of Time$)")
LOCALES = ["enUS", "deDE", "esES", "frFR"]
BUILD_INFO = os.environ.get("WOW_BUILD_INFO", os.path.expanduser(
    "~/Games/Battlenet/drive_c/Program Files (x86)/World of Warcraft/.build.info"))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "PlaceNames.lua")


def fetch(build, locale):
    request = urllib.request.Request(URL.format(build=build, locale=locale), headers={"User-Agent": "ForeverQuestLog tools"})
    with urllib.request.urlopen(request, timeout=120) as response:
        rows = csv.DictReader(io.StringIO(response.read().decode("utf-8")))
        return {r["ID"]: (r["MapName_lang"], r["InstanceType"]) for r in rows if r["InstanceType"] in INSTANCE_TYPES}


def installed_build():
    with open(BUILD_INFO, encoding="utf-8") as f:
        rows = list(csv.reader(f, delimiter="|"))
    head = [h.split("!")[0] for h in rows[0]]
    for row in rows[1:]:
        entry = dict(zip(head, row))
        if entry.get("Product") == "wowf":
            return entry["Version"]
    sys.exit("no Forever client (wowf) in " + BUILD_INFO)


def lua_string(text):
    if any(c in text for c in '"\\\n\r'):
        sys.exit("a name breaks the file format: %r" % text)
    return '"%s"' % text


def main():
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    build = sys.argv[1] if len(sys.argv) == 2 else installed_build()
    english = fetch(build, "enUS")
    if not english:
        sys.exit("wago.tools has no maps for build " + build)
    wanted = sorted(i for i, (name, _) in english.items() if name and not LEFTOVER.search(name))
    lines = ["-- Generated by tools/make_place_names.py from client build %s: do not edit." % build,
             "-- Dungeons and raids per language; esMX uses esES, other languages English.",
             "-- A name that is both (two maps) counts as a raid.",
             "local _, ns = ...",
             "local names = {"]
    for locale in LOCALES:
        names = english if locale == "enUS" else fetch(build, locale)
        def name(i): return (names.get(i) or english[i])[0]
        raids = sorted({name(i) for i in wanted if english[i][1] == "2"})
        dungeons = sorted({name(i) for i in wanted if english[i][1] == "1"} - set(raids))
        lines.append("    %s = {" % locale)
        lines.append("        dungeons = { %s }," % ", ".join(lua_string(n) for n in dungeons))
        lines.append("        raids = { %s }," % ", ".join(lua_string(n) for n in raids))
        lines.append("    },")
        print(locale, len(dungeons), "dungeons,", len(raids), "raids")
    lines += ["}",
              'local locale = GetLocale() == "esMX" and "esES" or GetLocale()',
              "ns.PlaceNames = names[locale] or names.enUS",
              ""]
    text = "\n".join(lines)
    # A new build with the same names leaves the file alone (only line 1 differs).
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as f:
            if f.read().split("\n")[1:] == text.split("\n")[1:]:
                return
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write(text)


if __name__ == "__main__":
    main()
